#!/usr/bin/env python3
"""Generate src/tuttable.h from ibus-tutcode's tutcode_rule.py.

Reads the vendored rule file (or fetches if missing) and produces a
C array of {stroke, sjis-code} pairs for single-kanji/kana outputs.
Entries are sorted alphabetically so tut_lookup could switch to binary
search in the future; linear scan still works.
"""

import os, re, sys, urllib.request

RULE_URL = "https://raw.githubusercontent.com/deton/ibus-tutcode/master/engine/tutcode_rule.py"
CACHE = os.path.join(os.path.dirname(__file__), "tutcode_rule.py")
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "tuttable.h")

def load():
    if not os.path.exists(CACHE):
        print(f"fetching {RULE_URL}", file=sys.stderr)
        data = urllib.request.urlopen(RULE_URL, timeout=15).read()
        with open(CACHE, "wb") as f:
            f.write(data)
    with open(CACHE, encoding="utf-8") as f:
        return f.read()

PAT = re.compile(r"u'([^']+)':\s*(?:u'([^']+)'|\(u'([^']+)',\s*u'([^']+)'\))")

def extract(content):
    """Yield (stroke, kanji/kana) pairs. For (kata, hira) tuples take hira."""
    seen = set()
    for m in PAT.finditer(content):
        key = m.group(1)
        val = m.group(2) if m.group(2) is not None else m.group(4)
        if key in seen:
            continue
        if len(val) != 1 or ord(val) < 0x80:
            continue
        # keys are lowercase ASCII letters or the punctuation ,.;/
        if not all((c.isalpha() and c.islower()) or c in ",.;/" for c in key):
            continue
        seen.add(key)
        yield key, val

def main():
    content = load()
    entries = []
    for k, v in extract(content):
        try:
            b = v.encode("shift_jis")
        except UnicodeEncodeError:
            continue
        if len(b) != 2:
            continue
        entries.append((k, b[0], b[1], v))
    entries.sort()
    out = []
    out.append("/* Generated by build/gen_tut_table.py. Do not edit by hand. */")
    out.append(f"/* Source: {RULE_URL} */")
    out.append(f"/* Entries: {len(entries)} */")
    out.append("")
    out.append("static const tut_entry tut_table[] = {")
    for k, b0, b1, v in entries:
        code = (b0 << 8) | b1
        # Escape non-ASCII kanji for the comment block -- source is SJIS.
        out.append(f'    {{"{k}", 0x{code:04x}}}, /* {v} */')
    out.append("    {0, 0}")
    out.append("};")
    out.append("")
    text = "\n".join(out)
    # Output as SJIS so that the inline comment kanji survive on the LSI-C86 side.
    with open(OUT, "wb") as f:
        f.write(text.encode("shift_jis", errors="replace"))
    print(f"wrote {OUT}: {len(entries)} entries", file=sys.stderr)

if __name__ == "__main__":
    main()
